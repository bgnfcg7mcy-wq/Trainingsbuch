create table public.trainings (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date date not null,
  content text not null check (char_length(btrim(content)) between 1 and 2000),
  paid boolean not null default false,
  created_at timestamptz not null default now()
);
create index trainings_user_date_idx on public.trainings(user_id, date desc, id desc);
alter table public.trainings enable row level security;
revoke all on public.trainings from anon;
grant select, insert, update, delete on public.trainings to authenticated;
grant usage, select on sequence public.trainings_id_seq to authenticated;
create policy trainings_select_own on public.trainings for select to authenticated using ((select auth.uid()) = user_id);
create policy trainings_insert_own on public.trainings for insert to authenticated with check ((select auth.uid()) = user_id);
create policy trainings_update_own on public.trainings for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy trainings_delete_own on public.trainings for delete to authenticated using ((select auth.uid()) = user_id);
